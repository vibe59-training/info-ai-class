// 예시 문항 모드의 문항 출처: QUIZ_SOURCES[교과][단원][난이도]
// 값은 문항 배열(직접 작성) 또는 문항 1개를 만드는 함수(수학 자동 생성)다.
// 문항 형식은 시스템 프롬프트의 type: quiz 규칙과 같다.
// { question, choices: [4개], answer: 1~4, explanation }

function q(question, choices, answer, explanation) {
  return { question, choices, answer, explanation };
}

function randInt(min, max) {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

function pick(list) {
  return list[randInt(0, list.length - 1)];
}

function digitsOf(n) {
  return String(n).split("").reverse().map(Number);
}

function countAddCarries(a, b) {
  const da = digitsOf(a);
  const db = digitsOf(b);
  let carry = 0;
  let count = 0;
  for (let i = 0; i < Math.max(da.length, db.length); i++) {
    const sum = (da[i] || 0) + (db[i] || 0) + carry;
    carry = sum >= 10 ? 1 : 0;
    count += carry;
  }
  return count;
}

function countSubBorrows(a, b) {
  const da = digitsOf(a);
  const db = digitsOf(b);
  let borrow = 0;
  let count = 0;
  for (let i = 0; i < da.length; i++) {
    const diff = da[i] - (db[i] || 0) - borrow;
    borrow = diff < 0 ? 1 : 0;
    count += borrow;
  }
  return count;
}

function countMulCarries(a, b) {
  return digitsOf(a).filter((d) => d * b >= 10).length;
}

// 받아올림을 잊었을 때 나오는 흔한 오답
function addWithoutCarry(a, b) {
  const da = digitsOf(a);
  const db = digitsOf(b);
  return Number(da.map((d, i) => (d + (db[i] || 0)) % 10).reverse().join(""));
}

// 받아내림 대신 큰 수에서 작은 수를 뺐을 때 나오는 흔한 오답
function subWithoutBorrow(a, b) {
  const da = digitsOf(a);
  const db = digitsOf(b);
  return Number(da.map((d, i) => Math.abs(d - (db[i] || 0))).reverse().join(""));
}

// 정답과 오답 후보로 보기 4개를 만든다. 정답 위치는 generateQuiz에서 섞는다.
function makeNumberItem(question, correct, candidates, format, explanation) {
  const distractors = [];
  const pool = candidates.concat([10, -10, 1, -1, 100, -100, 2, -2, 20, -20].map((d) => correct + d));
  for (const value of pool) {
    if (distractors.length === 3) break;
    if (Number.isInteger(value) && value > 0 && value !== correct && !distractors.includes(value)) {
      distractors.push(value);
    }
  }
  return q(question, [correct, ...distractors].map(format), 1, explanation);
}

const asIs = (n) => String(n);
const withUnit = (unit) => (n) => `${n}${unit}`;

function hourMinute(totalMinutes) {
  const h = Math.floor(totalMinutes / 60);
  const m = totalMinutes % 60;
  return m === 0 ? `${h}시` : `${h}시 ${m}분`;
}

function duration(totalMinutes) {
  const h = Math.floor(totalMinutes / 60);
  const m = totalMinutes % 60;
  if (h === 0) return `${m}분`;
  return m === 0 ? `${h}시간` : `${h}시간 ${m}분`;
}

function kmM(totalMeters) {
  const km = Math.floor(totalMeters / 1000);
  const m = totalMeters % 1000;
  return m === 0 ? `${km} km` : `${km} km ${m} m`;
}

function makeStringItem(question, correct, candidates, explanation) {
  const distractors = [];
  for (const value of candidates) {
    if (distractors.length === 3) break;
    if (value && value !== correct && !distractors.includes(value)) distractors.push(value);
  }
  return distractors.length === 3 ? q(question, [correct, ...distractors], 1, explanation) : null;
}

// 조건에 맞는 수를 찾을 때까지 다시 뽑는다.
function findPair(makePair, isValid) {
  for (let i = 0; i < 1000; i++) {
    const pair = makePair();
    if (isValid(...pair)) return pair;
  }
  throw new Error("조건에 맞는 수를 찾지 못했습니다.");
}

